CREATE TABLE VERIFICACAO_EMAIL (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_DIGEST VARCHAR(64) NOT NULL,
    CODIGO_DIGEST VARCHAR(64) NOT NULL,
    PUBLICO VARCHAR(20) NOT NULL,
    CAMPANHA VARCHAR(100) NOT NULL,
    FORMULARIO VARCHAR(100) NOT NULL,
    VERSAO_FORMULARIO INTEGER NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    DATA_CRIACAO TIMESTAMP(6) NOT NULL,
    EXPIRA_EM TIMESTAMP(6) NOT NULL,
    TENTATIVAS INTEGER NOT NULL DEFAULT 0,
    REENVIOS INTEGER NOT NULL DEFAULT 0,
    CODIGO_VALIDADO_EM TIMESTAMP(6),
    AUTORIZACAO_DIGEST VARCHAR(64) UNIQUE,
    AUTORIZACAO_EXPIRA_EM TIMESTAMP(6),
    CONSUMIDO_EM TIMESTAMP(6)
);

CREATE INDEX IDX_VERIFICACAO_EMAIL_REENVIO
    ON VERIFICACAO_EMAIL (EMAIL_DIGEST, DATA_CRIACAO);

CREATE INDEX IDX_VERIFICACAO_EMAIL_PENDENTE
    ON VERIFICACAO_EMAIL (EMAIL_DIGEST, PUBLICO, CAMPANHA, FORMULARIO, VERSAO_FORMULARIO, STATUS);
